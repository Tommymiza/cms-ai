export function SocialMediaRender({
  socialMediaType,
  className,
  hasBorder = false,
  invert = false,
}: {
  socialMediaType: SocialMedia["type"];
  className?: string;
  hasBorder?: boolean;
  invert?: boolean;
}) {
  switch (socialMediaType) {
    case "facebook":
      return (
        <IconContainer hasBorder={hasBorder} invert={invert}>
          <FacebookIcon className={className} />
        </IconContainer>
      );
    case "twitter":
      return (
        <IconContainer hasBorder={hasBorder} invert={invert}>
          <TwitterIcon className={className} width={16} height={16} />
        </IconContainer>
      );
    case "linkedin":
      return (
        <IconContainer hasBorder={hasBorder} invert={invert}>
          <LinkedinIcon className={className} />
        </IconContainer>
      );
    case "instagram":
      return (
        <IconContainer hasBorder={hasBorder} invert={invert}>
          <InstagramIcon className={className} />
        </IconContainer>
      );
    case "youtube":
      return (
        <IconContainer hasBorder={hasBorder} invert={invert}>
          <YoutubeIcon className={className} />
        </IconContainer>
      );
    case "pinterest":
      return (
        <IconContainer hasBorder={hasBorder} invert={invert}>
          <PinterestIcon className={className} />
        </IconContainer>
      );
    default:
      return null;
  }
}

function IconContainer({
  children,
  className,
  hasBorder = false,
  invert = false,
  ...props
}: {
  invert?: boolean;
  hasBorder?: boolean;
  children: React.ReactNode;
  className?: string;
} & React.HTMLAttributes<HTMLSpanElement>) {
  return (
    <span
      className={clsx(
        "ui-flex ui-items-center ui-border ui-p-1 ui-h-8 ui-w-8",
        hasBorder &&
          (invert
            ? "ui-border-text-color2 ui-rounded-full"
            : "ui-border-text-color ui-rounded-full"),
        !hasBorder && "ui-border-transparent",
        className
      )}
      {...props}
    >
      {children}
    </span>
  );
}
